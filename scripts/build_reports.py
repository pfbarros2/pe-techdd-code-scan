#!/usr/bin/env python3
"""Build reports/ (findings, heatmap md/html/png, 100-day plan) and the README
results block from results/*. Every number is read from results files."""
import html
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from techdd_scan.heatmap import build_heatmap, quality_backlog_count, remediation_items  # noqa: E402
from techdd_scan.matching import LINE_WINDOW, DECOY_WINDOW, RULES_VERSION  # noqa: E402

PRIMARY = "run1-nemotron-ultra"
RES = ROOT / "results"
REP = ROOT / "reports"
REP.mkdir(exist_ok=True)
summary = json.loads((RES / "summary.json").read_text())
manifest = json.loads((ROOT / "ground_truth" / "manifest.json").read_text())
planted = {p["id"]: p for p in manifest["planted"]}
decoys = {d["id"]: d for d in manifest["decoys"]}
runs = summary["runs"]
scores = {r["run"]: json.loads((RES / r["run"] / "score.json").read_text()) for r in runs}
prim = scores[PRIMARY]
ps = prim["summary"]
triage_path = RES / PRIMARY / "manual_triage.json"
triage = json.loads(triage_path.read_text()) if triage_path.exists() else None


def pct(x):
    return f"{x * 100:.1f}%"


def tok(n):
    return f"{n:,}" if isinstance(n, int) else "n/a"


def run_table():
    h = ("| Run | Model | Findings | Planted detected | Recall | Strict precision | TP findings | Duplicates | Near misses | "
         "Decoy FPs (decoys) | Unplanted | LLM calls | Input tokens | Output tokens | Elapsed |\n"
         "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|\n")
    for r in runs:
        h += (f"| {r['run']} | `{r['model']}` | {r['findings']} | {r['detected']}/{r['planted']} | {pct(r['recall'])} | "
              f"{pct(r['precision_strict'])} | {r['true_positive_findings']} | {r['duplicates']} | {r['near_miss']} | "
              f"{r['decoy_fp']} ({', '.join(r['decoys_flagged']) or '-'}) | {r['unplanted']} | {r['llm_calls']} | "
              f"{tok(r['input_tokens'])} | {tok(r['output_tokens'])} | {r['elapsed']} |\n")
    t = summary["totals"]
    h += (f"| **Total** | | | | | | | | | | | **{t['llm_calls']}** | **{tok(t['input_tokens'])}** | "
          f"**{tok(t['output_tokens'])}** | |\n")
    return h


def by_category_table(s):
    h = "| Category | Planted | Detected | Missed IDs |\n|---|---|---|---|\n"
    for cat, c in sorted(s["by_category"].items()):
        h += f"| {cat} | {c['planted']} | {c['detected']} | {', '.join(c['ids_missed']) or '-'} |\n"
    return h


def by_severity_table(s):
    h = "| Severity | Planted | Detected | Recall |\n|---|---|---|---|\n"
    for sev, c in s["by_severity"].items():
        r = c["detected"] / c["planted"] if c["planted"] else 0
        h += f"| {sev} | {c['planted']} | {c['detected']} | {pct(r)} |\n"
    return h


def consistency_table():
    n = len(runs)
    h = "| ID | Category | Severity | Runs detecting (of " + str(n) + ") | Runs |\n|---|---|---|---|---|\n"
    for pid, rs in summary["per_issue_runs"].items():
        p = planted[pid]
        h += f"| {pid} | {p['category']} | {p['severity']} | {len(rs)} | {', '.join(x.split('-')[0] for x in rs) or '-'} |\n"
    return h


def missed_section():
    out = ""
    for r in runs:
        ids = r["missed_ids"]
        out += f"- **{r['run']}** missed {len(ids)}: " + ("; ".join(f"{i} ({planted[i]['category']}, {planted[i]['severity']}) - {planted[i]['description']}" for i in ids) or "none") + "\n"
    return out


def decoy_section():
    out = ""
    for r in runs:
        for f in scores[r["run"]]["findings"]:
            if f["status"] == "decoy_false_positive":
                d = decoys[f["decoy_id"]]
                out += (f"- {r['run']}: **{f['decoy_id']}** `{d['file']}` (safe because: {d['why_safe']}) - tool said: "
                        f"\"{f['content'].strip().splitlines()[0][:180]}\"\n")
    return out or "- none\n"


# ---------------- findings.md ----------------
meta = prim.get("run_meta", {})
never = summary["planted_never_detected"]
every = summary["planted_detected_in_every_run"]
findings_md = f"""# Findings: Open Code Review on a fictional SaaS codebase

All numbers below are generated by `scripts/build_reports.py` from files in `results/`.
Codebase: `fixture/quillmoor-ledger` (FICTIONAL company, {len(planted)} planted issues, {len(decoys)} safe decoys).
Tool: `{meta.get('ocr_version', 'n/a')}`, `ocr scan` whole-codebase mode, unmodified, via an OpenAI-compatible
endpoint (`{meta.get('base_url', 'n/a')}`), `temperature` 0 sent via `extra_body`.
Scoring rules version {RULES_VERSION}: line window ±{LINE_WINDOW}, decoy window ±{DECOY_WINDOW} (see README "Scoring method").

## Per-run results

{run_table()}
- *Recall* = planted issues detected / {len(planted)}.
- *Strict precision* = findings matched to a planted issue (incl. duplicates) / all findings. Every unplanted
  finding counts against precision even if it is a real issue; see manual triage below.
- LLM calls are counted from OCR's local session log (`session_stats.json`); tokens are OCR's own run summary.

## Primary run ({PRIMARY}) - recall by category

{by_category_table(ps)}
## Primary run ({PRIMARY}) - recall by severity

{by_severity_table(ps)}
## Consistency across runs

- Detected in every run: {len(every)} of {len(planted)}.
- Detected in at least one run: {len(summary['planted_detected_in_any_run'])} of {len(planted)}.
- Never detected: {', '.join(never) if never else 'none'}.

{consistency_table()}
## Missed planted issues

{missed_section()}
## False positives on decoys (safe code that looks risky)

{decoy_section()}
"""
if triage:
    c = triage["counts"]
    findings_md += f"""## Manual triage of the primary run's other findings (judgement, not ground truth)

`results/{PRIMARY}/manual_triage.json` labels every {PRIMARY} finding the rules did not count as a true positive, plus
true-positive findings that were keyword mis-credits. Counts:

| Label | Count | Meaning |
|---|---|---|
""" + "".join(f"| {k} | {v} | {triage['labels'][k]} |\n" for k, v in c.items()) + """
Unplanted security observations the reviewer judged valid include plaintext password-reset tokens, no rate limiting on
auth endpoints, DNS rebinding against the webhook allowlist check, key reuse between JWT signing and field encryption,
and an unchecked padding strip in `decrypt_field`. The fixture was not designed to contain these, which is why strict
precision understates usefulness; the `incorrect` items are the genuine noise a reviewer must filter.
"""
audit_path = RES / "detection_audit.json"
if audit_path.exists():
    au = json.loads(audit_path.read_text())
    findings_md += "\n## Detection audit (manual check of keyword credits)\n\n" + au["method"] + "\n\n| Run | Credited issues with no on-topic finding | Mis-credited findings |\n|---|---|---|\n"
    for run, a in au["runs"].items():
        findings_md += f"| {run} | {len(a['credited_issues_without_on_topic_finding'])} | {len(a['miscredited_findings'])} |\n"
    findings_md += "\nMis-credits inflate the *TP findings* and *strict precision* columns slightly but did not change recall in the audited runs.\n"

missed_cats = {}
for r in runs:
    for pid in r["missed_ids"]:
        missed_cats.setdefault(planted[pid]["category"], set()).add(r["run"])
findings_md += "\n## Categories with misses\n\n" + ("".join(
    f"- {c}: missed in {', '.join(sorted(v))}\n" for c, v in sorted(missed_cats.items())) or "- none\n")

findings_md += """
## How to read this

This is a single small, synthetic codebase with deliberately obvious defects. High recall here does not predict
recall on a real, large, idiomatic codebase where defects are subtle and span many files. The value of the run is
the workflow (scan -> score -> heatmap -> remediation plan) and the measurement method, not the headline number.
"""
(REP / "findings.md").write_text(findings_md)

# ---------------- heatmap ----------------
rows = build_heatmap(prim, ps["by_category"])
backlog = quality_backlog_count(prim)
colors = {"RED": "#d9534f", "AMBER": "#f0ad4e", "GREEN": "#5cb85c", "n/a": "#cccccc"}
hm_md = f"""# Tech-DD code scan heatmap - LedgerLoop (Quillmoor Ledger Ltd, FICTIONAL)

Source: `results/{PRIMARY}/score.json` (`{meta.get('model')}`, {ps['findings_total']} findings). Generated by `scripts/build_reports.py`.

RAG rule (scanner view): RED if any finding in the domain falls in a category with rubric severity critical/high;
AMBER if only medium/low; GREEN if none. Categories are assigned by keyword rules in `src/techdd_scan/heatmap.py`;
the tool itself does not output a severity. The ground-truth columns show what was planted, to expose blind spots.

| Domain | RAG | Scanner findings | Planted (ground truth) | Planted detected |
|---|---|---|---|---|
""" + "".join(f"| {r['domain']} | **{r['rag']}** | {r['scanner_findings']} | {r['planted']} | {r['detected']} |\n" for r in rows) + f"""
Headline for an investment committee (illustrative, synthetic target): {ps['planted_detected']}/{ps['planted_total']} planted
issues surfaced; {ps['decoy_false_positives']} false alarm(s) on {len(decoys)} safe decoys; {ps['findings_total']} total findings, of which
{backlog} are general code-quality notes. Findings require expert validation before they appear in a DD report.
"""
(REP / "heatmap.md").write_text(hm_md)

rows_html = "".join(
    f"<tr><td>{html.escape(r['domain'])}</td><td style='background:{colors[r['rag']]};color:#fff;font-weight:bold;text-align:center'>{r['rag']}</td>"
    f"<td>{r['scanner_findings']}</td><td>{r['planted']}</td><td>{r['detected']}</td></tr>" for r in rows)
(REP / "heatmap.html").write_text(f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Tech-DD heatmap (fictional)</title>
<style>body{{font-family:Arial,sans-serif;max-width:900px;margin:24px auto;color:#222}}table{{border-collapse:collapse;width:100%}}
td,th{{border:1px solid #ccc;padding:8px}}th{{background:#333;color:#fff}}.note{{font-size:12px;color:#555}}</style></head><body>
<h2>Tech-DD code scan heatmap &mdash; LedgerLoop (Quillmoor Ledger Ltd, FICTIONAL)</h2>
<p class="note">Model: {html.escape(str(meta.get('model')))} &middot; {ps['findings_total']} findings &middot; {ps['planted_detected']}/{ps['planted_total']} planted issues detected &middot;
{ps['decoy_false_positives']} decoy false positive(s) &middot; synthetic demo data, not a real company.</p>
<table><tr><th>Domain</th><th>RAG</th><th>Scanner findings</th><th>Planted</th><th>Detected</th></tr>{rows_html}</table>
<p class="note">RAG: RED = any critical/high-rubric finding; AMBER = medium/low only; GREEN = none. Severity comes from a category rubric, not from the tool. Findings need expert validation.</p>
</body></html>
""")

import matplotlib  # noqa: E402
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

fig, ax = plt.subplots(figsize=(10, 0.55 * len(rows) + 1.6))
ax.axis("off")
cell = [[r["domain"], r["rag"], str(r["scanner_findings"]), f"{r['detected']}/{r['planted']}"] for r in rows]
tbl = ax.table(cellText=cell, colLabels=["Domain", "RAG", "Scanner findings", "Planted detected"],
               loc="center", cellLoc="left", colWidths=[0.48, 0.14, 0.18, 0.2])
tbl.auto_set_font_size(False)
tbl.set_fontsize(10)
tbl.scale(1, 1.5)
for i, r in enumerate(rows, start=1):
    tbl[(i, 1)].set_facecolor(colors[r["rag"]])
    tbl[(i, 1)].get_text().set_color("white")
    tbl[(i, 1)].get_text().set_weight("bold")
for j in range(4):
    tbl[(0, j)].set_facecolor("#333333")
    tbl[(0, j)].get_text().set_color("white")
ax.set_title(f"Tech-DD code scan heatmap - LedgerLoop (FICTIONAL)\n{meta.get('model')}: "
             f"{ps['planted_detected']}/{ps['planted_total']} planted detected, {ps['decoy_false_positives']} decoy FP, "
             f"{ps['findings_total']} findings", fontsize=11)
plt.tight_layout()
fig.savefig(REP / "heatmap.png", dpi=150, bbox_inches="tight")

# ---------------- remediation ----------------
items = remediation_items(prim)
rem = f"""# Sample 100-day remediation plan - LedgerLoop (FICTIONAL)

Derived from the scanner's own findings in `results/{PRIMARY}/score.json` (one line per category). Phase is set by
the category rubric (critical/high -> days 0-30, medium -> 31-60, low -> 61-100). "Ground-truth check" shows how the
underlying findings scored against the planted manifest, so you can see which lines a real engagement would still
need to triage. {backlog} general code-quality findings are left to the engineering backlog.

| Phase | Category | Rubric severity | Action | Locations (file:line) | Ground-truth check |
|---|---|---|---|---|---|
"""
for i in items:
    gt = ", ".join(f"{k}: {v}" for k, v in sorted(i["ground_truth"].items()))
    rem += f"| {i['phase']} | {i['category']} | {i['severity']} | {i['action']} | {'<br>'.join(i['locations'])} | {gt} |\n"
rem += """
Programme actions alongside the fixes (author's recommendation, not tool output): rotate every secret that has been in
source control; add secret scanning and SAST to CI; require a second reviewer on auth, payments and export code; re-run
the scan at day 100 and compare.
"""
(REP / "remediation_100_day.md").write_text(rem)

# ---------------- README block ----------------
aborted_note = ""
for ab in sorted(RES.glob("run*/aborted_run.json")):
    a = json.loads(ab.read_text())
    uu = a["usage_from_session_log"]
    aborted_note += (f"Aborted, not scored: `{a['label']}` (`{a['model']}`) - {len(a['files_completed'])} of 23 files reviewed, "
                     f"{a['llm_requests']} LLM calls, {uu.get('prompt_tokens', 0):,} prompt + {uu.get('completion_tokens', 0):,} completion "
                     f"tokens (from OCR's session log). Reason: {a['reason']}\n")
findings_md_extra = ("\n## Aborted runs\n\n" + aborted_note) if aborted_note else ""
(REP / "findings.md").write_text((REP / "findings.md").read_text() + findings_md_extra)
nem = [r for r in runs if "nemotron" in r["model"]]
rng = lambda k: (min(r[k] for r in nem), max(r[k] for r in nem))  # noqa: E731
block = f"""<!-- RESULTS:START (generated by scripts/build_reports.py - do not edit by hand) -->
{run_table()}
Primary run `{PRIMARY}`: **{ps['planted_detected']}/{ps['planted_total']} planted issues detected (recall {pct(ps['recall'])})**,
strict precision {pct(ps['precision_strict'])} ({ps['true_positive_findings']} of {ps['findings_total']} findings matched a planted issue),
{ps['decoy_false_positives']} false positive(s) on {len(decoys)} decoys, {ps['duplicate_findings']} duplicate(s).
Across {len(nem)} `nemotron-3-ultra` runs: detected {rng('detected')[0]}-{rng('detected')[1]} of {len(planted)}, findings {rng('findings')[0]}-{rng('findings')[1]}.
Across all {len(runs)} runs: {len(every)} issues found every time; never found: {', '.join(never) if never else 'none'}.
Totals for all runs: {summary['totals']['llm_calls']} LLM calls, {tok(summary['totals']['input_tokens'])} input + {tok(summary['totals']['output_tokens'])} output tokens.
{aborted_note}
<!-- RESULTS:END -->"""
readme = (ROOT / "README.md").read_text()
readme = re.sub(r"<!-- RESULTS:START.*?<!-- RESULTS:END -->", lambda _m: block, readme, flags=re.S)
(ROOT / "README.md").write_text(readme)
print("reports written")
